// Generates dist/index.js and dist/index.d.ts (gitignored) so design/components/bundle.js runs
// unchanged as an ES module. bundle.js is a browser IIFE that reads window.React and assigns
// window.QaReN; a module-scoped `window` holding React satisfies both by lexical scope, without
// touching the global, so the same file renders on the server and in the browser.
// Usage: bun scripts/build-adapter.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Component names from the bundle's `@ds-bundle` header, in header order. */
export function bundleNames(bundle: string): string[] {
  const header = /^\/\* @ds-bundle: (\{.*\}) \*\/\n/.exec(bundle);
  if (!header) throw new Error('bundle.js has no @ds-bundle header on its first line');
  const names = (JSON.parse(header[1]).components ?? []).map((c: { name: string }) => c.name);
  if (!names.length) throw new Error('the @ds-bundle header lists no components');
  for (const name of names)
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`unexpected component name: ${name}`);
  return names;
}

export function adapterJs(bundle: string, names: string[]): string {
  return [
    '// Generated by scripts/build-adapter.ts from design/components/bundle.js. Do not edit.',
    "import * as React from 'react';",
    'const window = { React };',
    bundle,
    'const QaReN = window.QaReN;',
    'export default QaReN;',
    ...names.map((n) => `export const ${n} = QaReN.${n};`),
    '',
  ].join('\n');
}

// A header name without a matching <Name>Props interface in index.d.ts fails the dist type-check.
export function adapterDts(names: string[]): string {
  const types = "'../design/components/index.js'";
  return [
    '// Generated by scripts/build-adapter.ts from design/components/index.d.ts. Do not edit.',
    "import type { FC } from 'react';",
    `import type { ${names.map((n) => `${n}Props`).join(', ')} } from ${types};`,
    `export type * from ${types};`,
    ...names.map((n) => `export declare const ${n}: FC<${n}Props>;`),
    `declare const QaReN: { ${names.map((n) => `${n}: typeof ${n}`).join('; ')} };`,
    'export default QaReN;',
    '',
  ].join('\n');
}

export function buildAdapter(pkgDir: string): string[] {
  const bundle = readFileSync(join(pkgDir, 'design/components/bundle.js'), 'utf8');
  const names = bundleNames(bundle);
  mkdirSync(join(pkgDir, 'dist'), { recursive: true });
  writeFileSync(join(pkgDir, 'dist/index.js'), adapterJs(bundle, names));
  writeFileSync(join(pkgDir, 'dist/index.d.ts'), adapterDts(names));
  return names;
}

if (import.meta.main) {
  const names = buildAdapter(fileURLToPath(new URL('..', import.meta.url)));
  console.log(`dist/index.js: ${names.length} components from design/components/bundle.js`);
}
